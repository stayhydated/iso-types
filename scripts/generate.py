#!/usr/bin/env python3
"""Generate typed catalogs from ISO snapshots, ICU4X names, and owned English FTL."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
from current_data import CurrentData

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'crates/iso-types-macros/data'
FTL = ROOT / 'crates/iso-types/i18n/en/iso-types'
CATALOGS = [
    ('639-1', 'Iso6391', 'alpha_2', '639-2'),
    ('639-2', 'Iso6392', 'alpha_3', '639-2'),
    ('639-3', 'Iso6393', 'alpha_3', '639-3'),
    ('3166-1', 'Iso3166_1', 'alpha_2', '3166-1'),
    ('3166-2', 'Iso3166_2', 'code', '3166-2'),
    ('4217', 'Iso4217', 'alpha_3', '4217'),
    ('15924', 'Iso15924', 'alpha_4', '15924'),
    ('5218', 'Iso5218', 'code', 'finite'),
    ('8601-weekday', 'Iso8601Weekday', 'code', 'finite'),
    ('8601-month', 'Iso8601Month', 'code', 'finite'),
]
ICU_CATALOGS = {'639-1', '639-2', '639-3', '3166-1', '4217', '15924', '8601-weekday', '8601-month'}


def literal(value):
    return json.dumps(value, ensure_ascii=False)


def markdown(value):
    return value.replace('\\', '\\\\').replace('[', '\\[').replace(']', '\\]')


def variant(code):
    return ''.join(part[0].upper() + part[1:].lower() for part in code.split('-'))


def entries(standard, code_key, source):
    records = json.loads((DATA / f'iso_{source}.json').read_text())[source]
    if source == 'finite':
        records = records[standard]
    return sorted((r for r in records if code_key in r), key=lambda r: r[code_key])


def write(path, content, check):
    if path.is_file() and path.read_text() == content:
        return
    if check:
        raise SystemExit(f'generated output differs: {path.relative_to(ROOT)}')
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--import-data', type=Path, help='iso-codes checkout to snapshot')
    args = parser.parse_args()
    if args.import_data:
        DATA.mkdir(parents=True, exist_ok=True)
        for source in sorted({s for _, _, _, s in CATALOGS} - {'finite'}):
            (DATA / f'iso_{source}.json').write_bytes((args.import_data / f'data/iso_{source}.json').read_bytes())
        revision = subprocess.check_output(['git', '-C', str(args.import_data), 'rev-parse', 'HEAD'], text=True).strip()
        manifest = {'source': 'https://salsa.debian.org/iso-codes-team/iso-codes', 'revision': revision,
                    'sha256': {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(DATA.glob('iso_*.json')) if p.name != 'iso_finite.json'}}
        (DATA / 'provenance.json').write_text(json.dumps(manifest, indent=2) + '\n')
    manifest = json.loads((DATA / 'provenance.json').read_text())
    for filename, expected in manifest['sha256'].items():
        if hashlib.sha256((DATA / filename).read_bytes()).hexdigest() != expected:
            raise SystemExit(f'source checksum mismatch: {filename}')
    current = CurrentData(DATA)
    icu_command = ['cargo', 'run', '--quiet', '-p', 'iso-types-icu-data', '--locked']
    if args.check:
        icu_command += ['--', '--check']
    subprocess.run(icu_command, cwd=ROOT, check=True)
    icu = json.loads((DATA / 'icu_english.json').read_text())['catalogs']
    if set(icu) != ICU_CATALOGS:
        raise SystemExit('ICU catalog ownership differs from the extractor')
    output = ['// Generated by scripts/generate.py from pinned ISO data, ICU4X names, and owned English FTL.\n']
    catalog_data = {}
    for standard, typename, code_key, source in CATALOGS:
        feature = '8601' if standard.startswith('8601-') else standard
        records = entries(standard, code_key, source)
        use_icu = standard in ICU_CATALOGS
        if use_icu:
            if set(icu[standard]) != {record[code_key] for record in records}:
                raise SystemExit(f'ICU snapshot codes differ from ISO source: {standard}')
            records = [record for record in records if icu[standard][record[code_key]] is not None]
        records = [record for record in records if current.includes(standard, record, code_key)]
        codes = [r[code_key] for r in records]
        assert len(set(codes)) == len(codes), standard
        variants = [r.get('variant', variant(r[code_key])) for r in records]
        assert len(set(variants)) == len(variants), standard
        ftl_path = FTL / f'{standard}.ftl'
        translations = {}
        if use_icu and ftl_path.exists():
            if args.check:
                raise SystemExit(f'ICU-owned catalog has stale FTL: {standard}')
            ftl_path.unlink()
        if not use_icu and ftl_path.is_file():
            for line in ftl_path.read_text().splitlines():
                if not line or line.startswith('#'):
                    continue
                key, value = line.split(' = ', 1)
                if any(c in value for c in '{}\n\r'):
                    raise SystemExit(f'{ftl_path}: catalog names must be literal single-line Fluent values')
                translations[key] = value
        catalog_entries = []
        for record, name in zip(records, variants):
            code = record[code_key]
            key = f'iso-{standard}-{code}'
            if not use_icu and key not in translations:
                if args.check:
                    raise SystemExit(f'missing English FTL entry: {key}')
                translations[key] = record['name']
            aliases = [record[k] for k in ('alpha_2', 'alpha_3', 'alpha_4', 'numeric') if k in record and record[k] != code]
            label = icu[standard][code] if use_icu else translations[key]
            if not label or any(c in label for c in '{}\n\r'):
                raise SystemExit(f'invalid English label: {key}')
            catalog_entries.append({'code': code, 'variant': name, 'name': label, 'id': key, 'aliases': aliases})
        expected_keys = {e['id'] for e in catalog_entries}
        if not use_icu and translations.keys() != expected_keys and args.check:
            raise SystemExit(f'English FTL keys differ from current catalog: {standard}')
        if not use_icu:
            write(ftl_path, f'## ISO {standard}\n\n' + ''.join(f"{e['id']} = {e['name']}\n" for e in catalog_entries), args.check)
        authority = 'Icu4x' if use_icu else 'Fluent'
        catalog_data[standard] = {'type': typename, 'feature': feature, 'source': authority, 'entries': catalog_entries}
        output += [f'#[cfg(feature = "{feature}")]\n', '#[derive(Clone, Copy, Debug, Eq, Hash, Ord, PartialEq, PartialOrd)]\n',
                   '#[repr(u16)]\n', f'/// Assigned codes in ISO {standard}; English labels are owned by {authority}.\n', f'pub enum {typename} {{\n']
        output += [f'    /// {markdown(e["name"])} (`{e["code"]}`).\n    {e["variant"]},\n' for e in catalog_entries]
        output += ['}\n', f'#[cfg(feature = "{feature}")]\nimpl {typename} {{\n',
                   f'    pub const STANDARD: &\'static str = "{standard}";\n',
                   f'    pub const LABEL_SOURCE: crate::LabelSource = crate::LabelSource::{authority};\n',
                   f'    pub const ALL: &\'static [Self] = &[{", ".join("Self::" + e["variant"] for e in catalog_entries)}];\n']
        methods = {'code': [e['code'] for e in catalog_entries], 'english_name': [e['name'] for e in catalog_entries],
                   'message_id': [e['id'] for e in catalog_entries]}
        metadata = sorted(set().union(*(r.keys() for r in records)) - {'name', 'variant', code_key})
        for field in metadata:
            if field in ('alpha_2', 'alpha_3', 'alpha_4', 'numeric', 'common_name', 'official_name', 'type', 'scope', 'parent'):
                method = 'kind' if field == 'type' else field
                values = ', '.join('Some(' + literal(r[field]) + ')' if field in r else 'None' for r in records)
                output += [f'    pub const fn {method}(self) -> Option<&\'static str> {{\n        const VALUES: &[Option<&str>] = &[{values}];\n        VALUES[self as usize]\n    }}\n']
        for method, values in methods.items():
            output += [f'    pub const fn {method}(self) -> &\'static str {{\n        const VALUES: &[&str] = &[{", ".join(literal(v) for v in values)}];\n        VALUES[self as usize]\n    }}\n']
        output += ['}\n', f'#[cfg(feature = "{feature}")]\nimpl std::str::FromStr for {typename} {{\n',
                   '    type Err = crate::ParseIsoCodeError;\n    fn from_str(input: &str) -> Result<Self, crate::ParseIsoCodeError> {\n',
                   '        if let Ok(index) = Self::ALL.binary_search_by(|entry| entry.code().cmp(input)) { return Ok(Self::ALL[index]); }\n']
        candidates = {}
        for e in catalog_entries:
            for alias in e['aliases']:
                candidates.setdefault(alias, set()).add(e['variant'])
        aliases = {a: next(iter(v)) for a, v in candidates.items() if a not in codes and len(v) == 1}
        if aliases:
            output += ['        match input {\n'] + [f'            {literal(alias)} => return Ok(Self::{name}),\n' for alias, name in sorted(aliases.items())] + ['            _ => {}\n        }\n']
        output += ['        Err(crate::ParseIsoCodeError { standard: Self::STANDARD, input: input.to_owned() })\n    }\n}\n',
                   f'#[cfg(feature = "{feature}")]\nimpl crate::IsoCode for {typename} {{\n',
                   '    const STANDARD: &\'static str = Self::STANDARD;\n    const LABEL_SOURCE: crate::LabelSource = Self::LABEL_SOURCE;\n    const ALL: &\'static [Self] = Self::ALL;\n',
                   '    fn code(self) -> &\'static str { self.code() }\n    fn english_name(self) -> &\'static str { self.english_name() }\n}\n',
                   f'#[cfg(all(feature = "{feature}", feature = "fmt"))]\nimpl std::fmt::Display for {typename} {{\n',
                   '    fn fmt(&self, f: &mut std::fmt::Formatter<\'_>) -> std::fmt::Result { f.write_str(self.english_name()) }\n}\n']
        output += [
                   f'#[cfg(all(feature = "{feature}", feature = "fluent"))]\nimpl es_fluent::FluentMessage for {typename} {{\n',
                   '    fn to_fluent_string_with(&self, localize: &mut es_fluent::FluentMessageLookup<\'_>) -> String {\n',
                   '        localize(self.fluent_key(), None)\n    }\n}\n',
                   f'#[cfg(all(feature = "{feature}", feature = "fluent"))]\nimpl {typename} {{\n',
                   '    pub const fn fluent_key(self) -> es_fluent::registry::StaticFluentMessageKey {\n        let id = match self {\n']
        output += [f'            Self::{e["variant"]} => es_fluent::registry::__macro::static_entry_id({literal(e["id"])}),\n' for e in catalog_entries]
        output += ['        };\n        es_fluent::registry::__macro::static_message_key("iso-types", es_fluent::registry::__macro::static_domain("iso-types"), id)\n    }\n}\n']
    rust = ''.join(output)
    formatted = subprocess.run(['rustfmt', '--edition', '2024', '--emit', 'stdout'], input=rust, text=True, capture_output=True, check=True).stdout
    write(ROOT / 'crates/iso-types/src/generated.rs', formatted, args.check)
    write(DATA / 'catalogs.json', json.dumps(catalog_data, ensure_ascii=False, indent=2) + '\n', args.check)
    resources = '// Generated by scripts/generate.py.\n'
    resources += 'pub(crate) const ENGLISH_RESOURCES: &[&str] = &[\n' + ''.join(f'    #[cfg(feature = "{c["feature"]}")]\n    include_str!("../i18n/en/iso-types/{s}.ftl"),\n' for s, c in catalog_data.items() if s not in ICU_CATALOGS) + '];\n'
    resources += 'pub(crate) fn icu_english_name(id: &str) -> Option<&\'static str> {\n'
    for standard, catalog in catalog_data.items():
        if standard in ICU_CATALOGS:
            resources += f'    #[cfg(feature = "{catalog["feature"]}")]\n    if let Some(code) = id.strip_prefix("iso-{standard}-") {{ return Some(code.parse::<crate::{catalog["type"]}>().ok()?.english_name()); }}\n'
    resources += '    let _ = id;\n    None\n}\n'
    resources = subprocess.run(['rustfmt', '--edition', '2024', '--emit', 'stdout'], input=resources, text=True, capture_output=True, check=True).stdout
    write(ROOT / 'crates/iso-types/src/resources.rs', resources, args.check)
    policy = subprocess.run(['rustfmt', '--edition', '2024', '--emit', 'stdout'], input=current.rust_locale_policy(), text=True, capture_output=True, check=True).stdout
    for crate in ['iso-types', 'iso-types-macros']:
        write(ROOT / f'crates/{crate}/src/current.rs', policy, args.check)
    print(f'{len(catalog_data)} catalogs, {sum(len(c["entries"]) for c in catalog_data.values())} assigned codes verified')


if __name__ == '__main__':
    main()
