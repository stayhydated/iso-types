"""Format and verify the complete generated output before writing it."""

from pathlib import Path
import os
import tempfile

ROOT = Path(__file__).resolve().parents[2]
GENERATED = "// Generated by python3 -m tools.codegen; edit the generator or source data.\n"


class OutputPlan:
    """Collect outputs so validation and formatting finish before any writes."""

    def __init__(self) -> None:
        self.files: dict[Path, bytes] = {}

    def add(self, path: Path, content: str | bytes) -> None:
        if path in self.files:
            raise ValueError(f"duplicate output: {path}")
        self.files[path] = content.encode("utf-8") if isinstance(content, str) else content

    def apply(self, *, check: bool) -> list[Path]:
        changed = [
            path for path, content in self.files.items()
            if not path.is_file() or path.read_bytes() != content
        ]
        if check:
            return changed
        for path in changed:
            path.parent.mkdir(parents=True, exist_ok=True)
            temporary = None
            try:
                with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as file:
                    temporary = Path(file.name)
                    file.write(self.files[path])
                temporary.chmod(0o644)
                os.replace(temporary, path)
            finally:
                if temporary is not None:
                    temporary.unlink(missing_ok=True)
        return changed
